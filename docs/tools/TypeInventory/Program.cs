using System.Security.Cryptography;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

if (args.Length != 3) throw new ArgumentException("Usage: TypeInventory <root> <UI-project> <Library-project>");
var root = Path.GetFullPath(args[0]);
var files = new List<object>();
var declarations = new List<(string Project, string Kind, string FullName, string Path, int Line)>();
string Relative(string file) => Path.GetRelativePath(root, file).Replace('\\', '/');
string Hash(string file) => Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(file)));
foreach (var project in args.Skip(1)) {
    foreach (var file in Directory.GetFiles(Path.Combine(root, project), "*.cs", SearchOption.AllDirectories).Order()) {
        var path = Relative(file);
        if (path.Split('/').Any(x => x is "bin" or "obj") ||
            System.Text.RegularExpressions.Regex.IsMatch(path, @"\.(g|g\.i|generated)\.cs$")) continue;
        var source = File.ReadAllText(file);
        if (source[..Math.Min(512, source.Length)].Contains("<auto-generated")) continue;
        files.Add(new { Project = project, Path = path, Sha256 = Hash(file) });
        var tree = CSharpSyntaxTree.ParseText(source);
        if (tree.GetDiagnostics().Any(x => x.Severity == DiagnosticSeverity.Error)) throw new Exception("Parse errors: " + path);
        foreach (var node in tree.GetRoot().DescendantNodes().OfType<TypeDeclarationSyntax>()) {
            if (node is not ClassDeclarationSyntax && node is not InterfaceDeclarationSyntax) continue;
            string TypeName(TypeDeclarationSyntax t) => t.Identifier.ValueText +
                (t.TypeParameterList is null ? "" : "`" + t.TypeParameterList.Parameters.Count);
            var parts = node.Ancestors().Reverse().Select(x => x switch {
                BaseNamespaceDeclarationSyntax n => n.Name.ToString(),
                TypeDeclarationSyntax t => TypeName(t), _ => null
            }).Where(x => x != null).Append(TypeName(node));
            declarations.Add((project, node is ClassDeclarationSyntax ? "class" : "interface",
                string.Join('.', parts), path, node.GetLocation().GetLineSpan().StartLinePosition.Line + 1));
        }
    }
}
var types = declarations.GroupBy(x => (x.Project, x.Kind, x.FullName)).OrderBy(x => x.Key.Kind).ThenBy(x => x.Key.FullName)
    .Select(g => new { g.Key.Project, g.Key.Kind, g.Key.FullName,
        Declarations = g.Select(x => new { x.Path, x.Line }).ToArray() }).ToArray();
var views = Directory.GetFiles(Path.Combine(root, args[1], "Views"), "*.axaml").Order()
    .Select(x => new { Path = Relative(x), Sha256 = Hash(x) }).ToArray();
var classes = types.Count(x => x.Kind == "class"); var interfaces = types.Count(x => x.Kind == "interface");
Console.WriteLine(JsonSerializer.Serialize(new {
    ReferenceRoot = root, Parser = "Roslyn C# syntax tree; class/interface only; all accessibilities",
    Exclusions = "UI/Library only; exclude tests, bin, obj, generated source",
    Deduplication = "Project + kind + namespace + containing types + name with generic arity",
    Summary = new { Classes = classes, Interfaces = interfaces, ViewFiles = views.Length,
        MinimumClasses = (int)Math.Ceiling(classes * .7), MinimumInterfaces = (int)Math.Ceiling(interfaces * .7), CSharpFiles = files.Count },
    SourceFiles = files, Types = types, Views = views
}, new JsonSerializerOptions { WriteIndented = true }));
