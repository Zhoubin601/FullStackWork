[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$ReferenceRoot,
    [string[]]$ProjectNames = @('DailyPoetryA', 'DailyPoetryA.Library'),
    [string]$ViewsRelativePath = 'DailyPoetryA/Views'
)

# Read-only inspection. JSON is written to stdout; the caller chooses its destination.
$ErrorActionPreference = 'Stop'
$referencePath = (Resolve-Path -LiteralPath $ReferenceRoot).Path
$dotnetPath = Split-Path -Parent (Get-Command dotnet -ErrorAction Stop).Source
$sdk = Get-ChildItem -LiteralPath (Join-Path $dotnetPath 'sdk') -Directory |
    Where-Object Name -Match '^8\.0\.\d+$' |
    Sort-Object { [version]$_.Name } -Descending |
    Select-Object -First 1
if (-not $sdk) { throw 'A .NET 8 SDK with bundled Roslyn assemblies is required.' }
$roslynPath = Join-Path $sdk.FullName 'Roslyn/bincore'
Add-Type -Path (Join-Path $roslynPath 'Microsoft.CodeAnalysis.dll')
Add-Type -Path (Join-Path $roslynPath 'Microsoft.CodeAnalysis.CSharp.dll')

$declarations = [System.Collections.Generic.List[object]]::new()
$sourceFiles = [System.Collections.Generic.List[object]]::new()
foreach ($projectName in $ProjectNames) {
    $projectPath = Join-Path $referencePath $projectName
    $files = Get-ChildItem -LiteralPath $projectPath -File -Recurse -Filter '*.cs' |
        Where-Object {
            $_.FullName -notmatch '[\\/](bin|obj)[\\/]' -and
            $_.Name -notmatch '\.(g|g\.i|generated)\.cs$'
        } | Sort-Object FullName
    foreach ($sourceFile in $files) {
        $sourceText = [System.IO.File]::ReadAllText($sourceFile.FullName)
        if ($sourceText.Substring(0, [Math]::Min(512, $sourceText.Length)) -match '<auto-generated') {
            continue
        }
        $relativePath = [System.IO.Path]::GetRelativePath($referencePath, $sourceFile.FullName).Replace('\', '/')
        $sourceFiles.Add([pscustomobject]@{
            Project = $projectName
            Path = $relativePath
            Sha256 = (Get-FileHash -LiteralPath $sourceFile.FullName -Algorithm SHA256).Hash
        })
        $tree = [Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree]::ParseText($sourceText)
        $parseErrors = @($tree.GetDiagnostics() | Where-Object { $_.Severity.ToString() -eq 'Error' })
        if ($parseErrors.Count -gt 0) { throw "C# parse errors in ${relativePath}: $parseErrors" }
        foreach ($node in $tree.GetRoot().DescendantNodes()) {
            $isClass = $node -is [Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax]
            $isInterface = $node -is [Microsoft.CodeAnalysis.CSharp.Syntax.InterfaceDeclarationSyntax]
            if (-not ($isClass -or $isInterface)) { continue }
            $namespaceParts = [System.Collections.Generic.List[string]]::new()
            $typeParts = [System.Collections.Generic.List[string]]::new()
            $typeName = $node.Identifier.ValueText
            if ($node.TypeParameterList) { $typeName += '`' + $node.TypeParameterList.Parameters.Count }
            $typeParts.Add($typeName)
            $ancestor = $node.Parent
            while ($null -ne $ancestor) {
                if ($ancestor -is [Microsoft.CodeAnalysis.CSharp.Syntax.BaseNamespaceDeclarationSyntax]) {
                    $namespaceParts.Insert(0, $ancestor.Name.ToString())
                } elseif ($ancestor -is [Microsoft.CodeAnalysis.CSharp.Syntax.TypeDeclarationSyntax]) {
                    $ownerName = $ancestor.Identifier.ValueText
                    if ($ancestor.TypeParameterList) { $ownerName += '`' + $ancestor.TypeParameterList.Parameters.Count }
                    $typeParts.Insert(0, $ownerName)
                }
                $ancestor = $ancestor.Parent
            }
            $fullName = ((@($namespaceParts) + @($typeParts)) -join '.')
            $declarations.Add([pscustomobject]@{
                Project = $projectName
                Kind = $(if ($isClass) { 'class' } else { 'interface' })
                FullName = $fullName
                Path = $relativePath
                Line = $node.GetLocation().GetLineSpan().StartLinePosition.Line + 1
            })
        }
    }
}

$types = @($declarations | Group-Object Project, Kind, FullName | ForEach-Object {
    $first = $_.Group[0]
    [pscustomobject]@{
        Project = $first.Project
        Kind = $first.Kind
        FullName = $first.FullName
        Declarations = @($_.Group | Sort-Object Path, Line | Select-Object Path, Line)
    }
} | Sort-Object Kind, FullName)
$views = @(Get-ChildItem -LiteralPath (Join-Path $referencePath $ViewsRelativePath) -File -Filter '*.axaml' |
    Sort-Object Name | ForEach-Object {
        [pscustomobject]@{
            Path = [System.IO.Path]::GetRelativePath($referencePath, $_.FullName).Replace('\', '/')
            Sha256 = (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash
        }
    })
$classCount = @($types | Where-Object Kind -eq 'class').Count
$interfaceCount = @($types | Where-Object Kind -eq 'interface').Count
[pscustomobject]@{
    ReferenceRoot = $referencePath
    Sdk = $sdk.Name
    Parser = 'Roslyn C# syntax tree; all class/interface accessibilities; no record/enum/struct counting'
    Exclusions = 'Only named UI/Library projects; no tests, bin/obj or generated sources'
    Deduplication = 'Project + kind + namespace + containing types + name with generic arity'
    Summary = [pscustomobject]@{
        Classes = $classCount
        Interfaces = $interfaceCount
        ViewFiles = $views.Count
        MinimumClasses = [int][Math]::Ceiling($classCount * 0.7)
        MinimumInterfaces = [int][Math]::Ceiling($interfaceCount * 0.7)
        CSharpFiles = $sourceFiles.Count
    }
    SourceFiles = @($sourceFiles)
    Types = $types
    Views = $views
} | ConvertTo-Json -Depth 8
