from pathlib import Path
import hashlib,json,subprocess,xml.etree.ElementTree as ET
from collections import Counter
from tree_sitter import Parser,Language
import tree_sitter_c_sharp

ROOT=Path(__file__).resolve().parents[3]
WORK=Path(__file__).resolve().parent
def digest(p): return hashlib.sha256(p.read_bytes()).hexdigest()
protected=list((ROOT/'raw').glob('*'))+list((ROOT/'output').rglob('*'))
before={str(p.relative_to(ROOT)):digest(p) for p in protected if p.is_file()}
(WORK/'protected-before.json').write_text(json.dumps(before,ensure_ascii=False,indent=2))
source=json.loads((ROOT/'docs/evidence/integrated-audit-20261024/source-hashes.json').read_text(encoding='utf-8-sig'))
mismatches=[r['path'] for r in source if digest(ROOT/r['path'])!=r['sha256']]
assert not mismatches,mismatches
parser=Parser(Language(tree_sitter_c_sharp.language()))
types={}; files=[]
for project in ['ReadJournal','ReadJournal.Library']:
 for f in sorted((ROOT/'Code'/project).rglob('*.cs')):
  if any(x in f.parts for x in ['bin','obj']) or f.name.endswith(('.g.cs','.g.i.cs','.generated.cs')): continue
  b=f.read_bytes()
  if b'<auto-generated' in b[:512]:continue
  tree=parser.parse(b);assert not tree.root_node.has_error,str(f)
  rel=str(f.relative_to(ROOT));files.append(rel)
  fs=[n for n in tree.root_node.named_children if n.type=='file_scoped_namespace_declaration']
  file_ns=fs[0].child_by_field_name('name').text.decode() if fs else ''
  def type_name(n):
   name=n.child_by_field_name('name').text.decode()
   arities=[c for c in n.named_children if c.type=='type_parameter_list']
   return name+('`'+str(len(arities[0].named_children)) if arities else '')
  def walk(n):
   if n.type in ['class_declaration','interface_declaration']:
    ancestors=[];p=n.parent
    while p:
     if p.type in ['class_declaration','interface_declaration','struct_declaration','record_declaration']:ancestors.append(type_name(p))
     if p.type=='namespace_declaration':ancestors.append(p.child_by_field_name('name').text.decode())
     p=p.parent
    names=([file_ns] if file_ns else [])+list(reversed(ancestors))+[type_name(n)]
    full='.'.join(names);kind=n.type.split('_')[0];key=(project,kind,full)
    types.setdefault(key,[]).append({'path':rel,'line':n.start_point.row+1})
   for child in n.named_children:walk(child)
  walk(tree.root_node)
views=sorted(str(f.relative_to(ROOT)) for f in (ROOT/'Code/ReadJournal/Views').glob('*.axaml'))
counts=Counter(k[1] for k in types)
inventory={'parser':'tree-sitter C#; UI/Library handwritten class/interface; partial deduplicated by project/kind/full name/generic arity; nested/default access included; records/structs/enums/tests/generated excluded','classes':counts['class'],'interfaces':counts['interface'],'csharp_files':len(files),'view_files':len(views),'views':views,'types':[{'project':k[0],'kind':k[1],'name':k[2],'declarations':v} for k,v in sorted(types.items())]}
(WORK/'type-inventory.json').write_text(json.dumps(inventory,ensure_ascii=False,indent=2))
assert counts['class']>=45 and counts['interface']>=7 and len(views)>=9
ev=ROOT/'docs/evidence/integrated-audit-20261024'
ns={'t':'http://microsoft.com/schemas/VisualStudio/TeamTest/2010'}
trx=ET.parse(ev/'full-verified.trx').getroot()
counters=trx.find('.//t:Counters',ns).attrib
results=Counter(r.attrib['outcome'] for r in trx.findall('.//t:UnitTestResult',ns))
assert counters['total']=='353' and counters['passed']=='351' and counters['failed']=='0'
assert results['NotExecuted']==2,results
out=ROOT/'output/v2';out.mkdir(exist_ok=True)
archive=out/'20261025-阅记-源码-v2.zip'
if not archive.exists():
 package=json.loads(subprocess.check_output(['python',str(ROOT/'Code/pack.py'),str(archive)],text=True))
else:
 import zipfile
 with zipfile.ZipFile(archive) as z:
  entries=(ROOT/'Code/delivery-files.txt').read_text().splitlines()
  assert entries==z.namelist()
  for entry in entries:assert hashlib.sha256(z.read(entry)).hexdigest()==digest(ROOT/'Code'/entry)
 package={'Path':str(archive),'Bytes':archive.stat().st_size,'Files':len(entries),'Sha256':digest(archive)}
meta={'commit':subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),'code_hashes_verified':len(source),'mismatches':mismatches,'test_counters':counters,'outcomes':dict(results),'inventory':{k:v for k,v in inventory.items() if k not in ['types','views']},'package':package,'reused_test_date':'2026-10-24','report_date':'2026-10-25','tests_rerun_this_round':False}
(WORK/'facts.json').write_text(json.dumps(meta,ensure_ascii=False,indent=2))
print(json.dumps(meta,ensure_ascii=False,indent=2))
